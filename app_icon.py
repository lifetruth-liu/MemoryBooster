def icon_bytes():
    """还原出 ICO 的原始字节。"""
    return zlib.decompress(base64.b64decode("".join(_ICO_Z)))


_CACHE = None


def icon_file():
    """把图标落地成临时 .ico 并返回路径（Tk/SetForegroundWindow 都吃文件路径）。"""
    global _CACHE
    if _CACHE and os.path.exists(_CACHE):
        return _CACHE
    try:
        data = icon_bytes()
    except Exception:
        return ""
    try:
        d = os.path.join(os.environ.get("TEMP") or os.environ.get("TMP") or ".",
                         "MemoryBooster.icon")
        os.makedirs(d, exist_ok=True)
        p = os.path.join(d, "app.ico")
        # 内容一致就不重复写盘
        try:
            if os.path.getsize(p) == len(data):
                with open(p, "rb") as f:
                    if f.read() == data:
                        _CACHE = p
                        return p
        except Exception:
            pass
        with open(p, "wb") as f:
            f.write(data)
        _CACHE = p
        return p
    except Exception:
        return ""
